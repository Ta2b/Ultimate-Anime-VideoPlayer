using Bytes = std::vector<std::uint8_t>;

// Lit `data` par morceaux d'au plus `chunk` octets.
core::InflateRead reader(const Bytes& data, std::size_t chunk) {
  return [&data, chunk, at = std::size_t{0}](std::span<std::uint8_t> buffer) mutable {
    const std::size_t n = std::min({buffer.size(), chunk, data.size() - at});
    std::copy_n(data.begin() + static_cast<std::ptrdiff_t>(at), n, buffer.begin());
    at += n;
    return n;
  };
}

std::expected<Bytes, Refusal> inflate_all(const Bytes& compressed, std::size_t chunk = 1U << 16) {
  Bytes out;
  auto done = core::inflate_raw(reader(compressed, chunk), [&](std::span<const std::uint8_t> bytes) {
    out.insert(out.end(), bytes.begin(), bytes.end());
    return true;
  });
  if (!done) return std::unexpected(done.error());
  CHECK(*done == out.size());
  return out;
}

// Les octets que la fabrique a compressés (même générateur que celui du fixture).
Bytes skewed(std::size_t count) {
  Bytes out;
  std::uint32_t x = 777;
  for (std::size_t i = 0; i < count; ++i) {
    x = (x * 1103515245U + 12345U) & 0x7fffffffU;
    out.push_back(static_cast<std::uint8_t>(((x >> 16) % 9U) * (((x >> 8) % 3U) + 1U)));
  }
  return out;
}

